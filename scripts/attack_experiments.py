# ============================================================
# 8. Request Signing
# ============================================================

def sign_request(
    request,
    private_key
):

    return private_key.sign(
        canonical_json(request)
    )


# ============================================================
# 9. Signature Verification
# ============================================================

def verify_signature(
    data,
    signature,
    public_key
):

    try:

        public_key.verify(
            signature,
            canonical_json(data)
        )

        return True

    except InvalidSignature:

        return False


# ============================================================
# 10. ABT Freshness
# ============================================================

def verify_abt_freshness(abt):

    now = datetime.now(timezone.utc)

    issued_at = datetime.fromisoformat(
        abt["issued_at"]
    )

    expires_at = datetime.fromisoformat(
        abt["expires_at"]
    )

    return (
        issued_at <= now <= expires_at
    )


# ============================================================
# 11. Endpoint Binding
# ============================================================

def verify_endpoint_binding(
    abt,
    request
):

    return (
        abt["endpoint"]
        ==
        request["endpoint"]
    )


# ============================================================
# 12. ZK Permission Verification
#
# Prototype authorization predicate.
#
# Replace this function with the actual zk-SNARK verifier
# when integrating this experiment with your implementation.
# ============================================================

def verify_zk_permission(
    abt,
    request
):

    action = request["action"]

    return (
        action in abt["permissions"]
        and
        action in abt["capabilities"]
    )


# ============================================================
# 13. OPA-Style Policy Evaluation
# ============================================================

def opa_policy_check(
    abt,
    request,
    zk_verified
):

    action = request["action"]

    if abt["role"] != AUTHORIZED_ROLE:

        return False

    if not zk_verified:

        return False

    if action not in abt["permissions"]:

        return False

    if action not in abt["capabilities"]:

        return False

    return True


# ============================================================
# 14. ARIA Authorization Path
# ============================================================

def aria_authorization_path(
    abt,
    abt_signature,
    request,
    request_signature,
    public_key
):

    # --------------------------------------------------------
    # Identity verification
    # --------------------------------------------------------

    if not verify_signature(
        abt,
        abt_signature,
        public_key
    ):

        return "DENY", "Invalid ABT signature"


    # --------------------------------------------------------
    # ABT validity
    # --------------------------------------------------------

    if not verify_abt_freshness(abt):

        return "DENY", "Expired ABT"


    # --------------------------------------------------------
    # Request integrity
    # --------------------------------------------------------

    if not verify_signature(
        request,
        request_signature,
        public_key
    ):

        return "DENY", "Invalid request signature"


    # --------------------------------------------------------
    # Endpoint binding
    # --------------------------------------------------------

    if not verify_endpoint_binding(
        abt,
        request
    ):

        return "DENY", "Endpoint binding failure"


    # --------------------------------------------------------
    # ZK permission verification
    # --------------------------------------------------------

    zk_verified = verify_zk_permission(
        abt,
        request
    )

    if not zk_verified:

        return (
            "DENY",
            "ZK permission verification failed"
        )


    # --------------------------------------------------------
    # OPA policy evaluation
    # --------------------------------------------------------

    policy_allowed = opa_policy_check(
        abt,
        request,
        zk_verified
    )

    if not policy_allowed:

        return (
            "DENY",
            "OPA policy violation"
        )


    return (
        "ALLOW",
        "Authorization successful"
    )


