def opa_policy_check(
    abt,
    request,
    zk_verified
):

    action = request["action"]

    if abt["role"] != AUTHORIZED_ROLE:

        return False

    if not zk_verified:

        return False

    if action not in abt["permissions"]:

        return False

    if action not in abt["capabilities"]:

        return False

    return True


# ============================================================
# 14. Complete ARIA Authorization
# ============================================================

def aria_authorize(
    abt,
    abt_signature,
    request,
    request_signature,
    public_key
):

    # --------------------------------------------------------
    # Step 1: Verify ABT signature
    # --------------------------------------------------------

    if not verify_abt_signature(
        abt,
        abt_signature,
        public_key
    ):

        return {
            "decision": "DENY",
            "reason": "Invalid ABT signature",
            "remediation_executed": False
        }


    # --------------------------------------------------------
    # Step 2: Verify ABT validity
    # --------------------------------------------------------

    if not verify_abt_freshness(abt):

        return {
            "decision": "DENY",
            "reason": "Expired ABT",
            "remediation_executed": False
        }


    # --------------------------------------------------------
    # Step 3: Verify request signature
    # --------------------------------------------------------

    if not verify_request_signature(
        request,
        request_signature,
        public_key
    ):

        return {
            "decision": "DENY",
            "reason": "Invalid request signature",
            "remediation_executed": False
        }


    # --------------------------------------------------------
    # Step 4: Verify endpoint binding
    # --------------------------------------------------------

    if not verify_endpoint_binding(
        abt,
        request
    ):

        return {
            "decision": "DENY",
            "reason": "Endpoint binding failure",
            "remediation_executed": False
        }


    # --------------------------------------------------------
    # Step 5: Replay detection
    # --------------------------------------------------------

    fresh, reason = verify_request_freshness(
        request
    )

    if not fresh:

        return {
            "decision": "DENY",
            "reason": reason,
            "remediation_executed": False
        }


    # --------------------------------------------------------
    # Step 6: ZK permission verification
    # --------------------------------------------------------

    zk_verified = verify_zk_permission(
        abt,
        request
    )

    if not zk_verified:

        return {
            "decision": "DENY",
            "reason": "ZK permission verification failed",
            "remediation_executed": False
        }


    # --------------------------------------------------------
    # Step 7: OPA policy evaluation
    # --------------------------------------------------------

    policy_allowed = opa_policy_check(
        abt,
        request,
        zk_verified
    )

    if not policy_allowed:

        return {
            "decision": "DENY",
            "reason": "OPA policy violation",
            "remediation_executed": False
        }


    # --------------------------------------------------------
    # Step 8: Record request as consumed
    # --------------------------------------------------------

    used_request_ids.add(
        request["request_id"]
    )


    # --------------------------------------------------------
    # Step 9: Execute privileged remediation
    # --------------------------------------------------------

    return {
        "decision": "ALLOW",
        "reason": "Authorized fresh request",
        "remediation_executed": True
    }


