# ============================================================
# 2. ABT Structure
# ============================================================

def create_abt(
    agent_id,
    role,
    endpoint,
    permissions,
    capabilities,
    public_key_id,
    attestation_id
):
    now = datetime.now(timezone.utc)

    return {
        "agent_id": agent_id,
        "role": role,
        "endpoint": endpoint,
        "permissions": permissions,
        "capabilities": capabilities,
        "issued_at": now.isoformat(),
        "expires_at": (now + timedelta(minutes=30)).isoformat(),
        "nonce": secrets.token_hex(16),
        "attestation_id": attestation_id,
        "public_key_id": public_key_id
    }


# ============================================================
# 3. Canonical ABT Encoding
# ============================================================

def canonical_abt(abt):
    return json.dumps(
        abt,
        sort_keys=True,
        separators=(",", ":")
    ).encode()


# ============================================================
# 4. ABT Signing
# ============================================================

def sign_abt(abt, private_key):
    return private_key.sign(canonical_abt(abt))


# ============================================================
# 5. ABT Signature Verification
# ============================================================

def verify_abt_signature(abt, signature, public_key):
    try:
        public_key.verify(
            signature,
            canonical_abt(abt)
        )
        return True
    except InvalidSignature:
        return False


# ============================================================
# 6. Freshness / Expiry Check
# ============================================================

def verify_abt_freshness(abt):

    now = datetime.now(timezone.utc)

    issued_at = datetime.fromisoformat(
        abt["issued_at"]
    )

    expires_at = datetime.fromisoformat(
        abt["expires_at"]
    )

    if now < issued_at:
        return False

    if now > expires_at:
        return False

    return True


# ============================================================
# 7. Endpoint Binding
# ============================================================

def verify_endpoint_binding(abt, endpoint):

    return abt["endpoint"] == endpoint


# ============================================================
# 8. ZK Permission Verification
#
# IMPORTANT:
# This function is an interface for the actual zk-SNARK
# verifier in your prototype.
#
# For this experiment harness, we model the authorization
# predicate. Replace this function with your actual
# Verify_zk(proof, public_inputs) implementation when running
# the final experiment.
# ============================================================

def verify_zk_permission(abt, requested_action):

    # Authorization predicate represented by the prototype:
    # the requested capability must be bound to the ABT.

    return (
        requested_action in abt["capabilities"]
        and requested_action in abt["permissions"]
    )


# ============================================================
# 9. OPA-style Policy Evaluation
# ============================================================

def opa_policy_check(
    abt,
    requested_action,
    authenticated,
    zk_verified
):

    if not authenticated:
        return "DENY"

    if not zk_verified:
        return "DENY"

    if abt["role"] != AUTHORIZED_ROLE:
        return "DENY"

    if requested_action not in abt["permissions"]:
        return "DENY"

    if requested_action not in abt["capabilities"]:
        return "DENY"

    return "ALLOW"


# ============================================================
# 10. Complete ARIA Authorization Path
# ============================================================

def aria_authorize(
    abt,
    signature,
    registered_public_key,
    endpoint,
    requested_action
):

    # Step 1: ABT identity verification
    signature_valid = verify_abt_signature(
        abt,
        signature,
        registered_public_key
    )

    if not signature_valid:
        return {
            "decision": "DENY",
            "reason": "Invalid ABT signature",
            "remediation_executed": False
        }

    # Step 2: ABT freshness
    if not verify_abt_freshness(abt):
        return {
            "decision": "DENY",
            "reason": "Expired or invalid ABT",
            "remediation_executed": False
        }

    # Step 3: Endpoint binding
    if not verify_endpoint_binding(
        abt,
        endpoint
    ):
        return {
            "decision": "DENY",
            "reason": "Endpoint binding failure",
            "remediation_executed": False
        }

    # Step 4: ZK permission verification
    zk_verified = verify_zk_permission(
        abt,
        requested_action
    )

    # Step 5: OPA policy evaluation
    decision = opa_policy_check(
        abt,
        requested_action,
        authenticated=True,
        zk_verified=zk_verified
    )

    if decision != "ALLOW":
        return {
            "decision": "DENY",
            "reason": "Authorization policy violation",
            "remediation_executed": False
        }

    # Step 6: Privileged remediation
    return {
        "decision": "ALLOW",
        "reason": "Authorized request",
        "remediation_executed": True
    }


